#!/usr/bin/env python3
"""Label the first_round_step{1..5} selector dataset with Template F (v5_substep_cite)
answers generated by Codex.

For every row we rebuild the selector prompt with Template F. The prompt text is
explicit and editable in ``prompt_template_F.py`` (``build_prompt``) -- tune it there.
The placeholders are filled with:
  * ``{{problem}}``  = the row's (already hint-line-stripped) ``problem``
  * ``{{trace}}``    = the row's ``reasoning_trace`` (the trace shown to the selector)
  * ``{{hints}}``    = the full candidate hint pool, joined by ``problem_id`` from
                       dataset/dapo-3139-hint-verl-mt-clean.parquet (extra_info.hint).
                       These are first-round calls (call_index == 0), so no hint has
                       been applied yet and the full pool == the candidate pool.

Each prompt is sent to a fresh Codex CLI session (same launcher as
``data_pipeline/generate_hint_sets.py``), run ``--workers`` at a time. We record, per
row: the parsed Template F answer, the original selector answer already stored in
the dataset, the number of words in the generated answer, and the wall-clock time
the Codex call took.

Output layout (results grouped under a per-step dir; one JSON per call. problem_id
is a sub-dir because it is not unique even within a step, so the file is keyed by
request_id, which is unique per selector call):

    results/runs/run_{timestamp}/                 (or results/debug/run_{timestamp}/ with --debug)
        label_dataset_templateF.py                <- copy of the script that produced this run
        run_config.json                           <- the resolved CLI config
        results.jsonl                             <- aggregate, one record per line
        step{N}/
            <problem_id>/
                {request_id}.json                 <- the per-call result

Examples:
    python label_dataset_templateF.py -n 5 --debug          # first 5 rows of EACH step (25), into results/debug/
    python label_dataset_templateF.py --steps 2 -n 1 --workers 1
    python label_dataset_templateF.py                       # all 500 rows, into results/runs/
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime
from pathlib import Path
from typing import Any, Optional

import pandas as pd
from tqdm import tqdm

HERE = Path(__file__).resolve().parent           # .../hint_rl/selector/test_cite
SELECTOR = HERE.parent                           # .../hint_rl/selector
PROJ = SELECTOR.parent                           # .../hint_rl
sys.path.insert(0, str(HERE))                    # prompt_template_F (the editable Template F prompt)
sys.path.insert(0, str(SELECTOR))                # run_hint_selection_model (parse_output), seletor_prompt
sys.path.insert(0, str(PROJ / "data_pipeline")) # hint_generation_utils

import prompt_template_F                                    # noqa: E402  (explicit prompt module; snapshotted per run)
from prompt_template_F import build_prompt                 # noqa: E402  (tune the prompt in test_cite/prompt_template_F.py)
from run_hint_selection_model import parse_output          # noqa: E402  (LaTeX-tolerant)
from hint_generation_utils import CodexCLIClient, safe_path_name  # noqa: E402

DATASET_DIR = HERE / "dataset"                   # first_round_step*.parquet (moved into test_cite/)
TRAIN_PARQUET = PROJ / "dataset" / "dapo-3139-hint-verl-mt-clean.parquet"
RESULTS_ROOT = HERE / "results"
SESSION_DIR = HERE / ".codex_label_sessions"
VARIANT_NAME = "v5_substep_cite"                 # Template F


# ============================================================================
# Codex output schema (advisory) + helpers
# ============================================================================
def schema_templateF() -> dict[str, Any]:
    """Advisory JSON schema for the Template F (v5_substep_cite) output."""
    return {
        "type": "object",
        "additionalProperties": False,
        "required": [
            "completed_substeps", "major_step_id", "reasoning_of_major_step",
            "confidence_of_major_step", "hint_id", "reasoning_of_hint",
            "confidence_of_hint", "hint",
        ],
        "properties": {
            "completed_substeps": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["hint_id", "quote", "why"],
                    "properties": {
                        "hint_id": {"type": "string"},
                        "quote": {"type": "string"},
                        "why": {"type": "string"},
                    },
                },
            },
            "major_step_id": {"type": "integer"},
            "reasoning_of_major_step": {"type": "string"},
            "confidence_of_major_step": {"type": "integer", "minimum": 1, "maximum": 5},
            "hint_id": {"type": "string"},
            "reasoning_of_hint": {"type": "string"},
            "confidence_of_hint": {"type": "integer", "minimum": 1, "maximum": 5},
            "hint": {"type": "string"},
        },
    }


def load_pid2hint() -> dict[str, str]:
    df = pd.read_parquet(TRAIN_PARQUET)
    out: dict[str, str] = {}
    for ei in df["extra_info"]:
        pid = ei.get("problem_id")
        if pid is not None:
            out[str(pid)] = ei.get("hint")
    return out


def make_client(cfg: argparse.Namespace) -> CodexCLIClient:
    return CodexCLIClient(
        model=cfg.model,
        timeout=cfg.timeout,
        reasoning_effort=cfg.reasoning_effort,
        retries=cfg.retries,
        codex_bin=cfg.codex_bin,
        workdir=HERE,
        session_dir=SESSION_DIR,
    )


def _count_text_words(parsed: Optional[dict]) -> int:
    """Words across the human-readable string fields of a Template F answer."""
    if not isinstance(parsed, dict):
        return 0
    parts: list[str] = []
    for k in ("reasoning_of_major_step", "reasoning_of_hint", "hint"):
        v = parsed.get(k)
        if isinstance(v, str):
            parts.append(v)
    for cs in parsed.get("completed_substeps") or []:
        if isinstance(cs, dict):
            for k in ("quote", "why"):
                v = cs.get(k)
                if isinstance(v, str):
                    parts.append(v)
    return len(" ".join(parts).split())


def run_codex(client: CodexCLIClient, name: str, prompt: str, retries: int) -> dict[str, Any]:
    """Run one Codex session for ``prompt``; parse leniently. Returns a result dict.

    Drives its own retry loop so we keep the raw text + latency even when the strict
    JSON parse used by CodexCLIClient.call_json would reject valid LaTeX-heavy output.
    """
    schema = schema_templateF()
    last: dict[str, Any] = {}
    t0 = time.time()
    for attempt in range(retries + 1):
        step_dir = client._make_step_dir(name=name, attempt=attempt)
        out_path = step_dir / f"{name}.json"
        retry_note = None if attempt == 0 else (
            "The previous response did not produce a parseable <output> block with "
            "valid JSON. Write exactly one <output>...</output> block to the file."
        )
        agent_prompt = client._build_agent_prompt(
            name=name, prompt=prompt, schema=schema,
            output_path=out_path, retry_note=retry_note,
        )
        (step_dir / f"{name}_agent_prompt.txt").write_text(agent_prompt, encoding="utf-8")
        try:
            res = client._run(agent_prompt)
            stdout, stderr, rc = res.stdout or "", res.stderr or "", res.returncode
        except Exception as exc:  # noqa: BLE001 -- subprocess/timeout failure
            last = {"parsed": None, "raw": "", "parse_error": repr(exc),
                    "returncode": None, "stderr_preview": "", "output_path": str(out_path)}
            continue
        raw = out_path.read_text(encoding="utf-8") if out_path.exists() else ""
        parsed, perr = parse_output(raw) if raw else (None, "no output file")
        if parsed is None and stdout:
            p2, e2 = parse_output(stdout)
            if p2 is not None:
                parsed, perr = p2, None
                if not raw:
                    raw = stdout
        last = {
            "parsed": parsed, "raw": raw, "parse_error": perr,
            "returncode": rc, "stderr_preview": stderr[:2000],
            "output_path": str(out_path),
        }
        if parsed is not None and rc == 0:
            break
        time.sleep(min(2 ** attempt, 20))
    last["latency_s"] = round(time.time() - t0, 3)
    return last


# ============================================================================
# Job building + per-problem saving
# ============================================================================
def per_problem_path(run_dir: Path, job: dict[str, Any]) -> Path:
    """results/<mode>/run_{ts}/step{N}/<problem_id>/<request_id>.json.

    Results are grouped under a per-step directory. problem_id is a sub-directory
    (it is not unique even within a step); the file is keyed by request_id, which
    is unique per selector call.
    """
    return (run_dir / f"step{job['step']}" / safe_path_name(job["problem_id"])
            / f"{safe_path_name(job['request_id'])}.json")


def build_jobs(pid2hint: dict[str, str], steps: list[int], num_problems: Optional[int],
               run_dir: Path) -> list[dict[str, Any]]:
    jobs: list[dict[str, Any]] = []
    for step in steps:
        path = DATASET_DIR / f"first_round_step{step}.parquet"
        if not path.exists():
            print(f"warn: missing {path}", file=sys.stderr)
            continue
        df = pd.read_parquet(path)
        if num_problems is not None:
            df = df.head(num_problems)        # first N rows of THIS step
        for i, row in df.iterrows():
            request_id = str(row["request_id"])
            pid = str(row["problem_id"])
            hints = pid2hint.get(pid)
            job = {
                "uid": f"{step}:{request_id}", "step": step, "step_file": path.name,
                "row_index": int(i), "problem_id": pid, "request_id": request_id,
                "problem": row["problem"],                 # input problem statement
                "reasoning_trace": row["reasoning_trace"], # input trace shown to the selector
                "budget": int(row["budget"]) if pd.notna(row["budget"]) else None,
                "strategy": row["strategy"],
                "call_index": int(row["call_index"]) if pd.notna(row["call_index"]) else None,
                "original_major_step_id": int(row["major_step_id"]) if pd.notna(row["major_step_id"]) else None,
                "original_answer_raw": row["selector_response"],
            }
            try:
                job["original_answer"] = json.loads(row["selection"])
            except (json.JSONDecodeError, TypeError):
                job["original_answer"] = None
            # record the candidate hint pool (the {{hints}} input) alongside the result
            if hints:
                try:
                    job["hint_pool"] = json.loads(hints)
                except (json.JSONDecodeError, TypeError):
                    job["hint_pool"] = hints
            else:
                job["hint_pool"] = None
            if not hints:
                job["error"] = f"no hint pool for problem_id {pid}"
                job["_prompt"] = None
            else:
                job["error"] = None
                job["_prompt"] = build_prompt(row["problem"], row["reasoning_trace"], hints)
            jobs.append(job)

    # Resume: drop jobs already saved in this run dir (relevant with --resume-dir).
    jobs = [j for j in jobs if not per_problem_path(run_dir, j).exists()]
    return jobs


def process(client: CodexCLIClient, job: dict[str, Any], cfg: argparse.Namespace) -> dict[str, Any]:
    rec = {k: v for k, v in job.items() if k != "_prompt"}
    rec["model"] = cfg.model
    rec["reasoning_effort"] = cfg.reasoning_effort
    rec["timestamp"] = datetime.now().isoformat(timespec="seconds")
    if cfg.debug:
        rec["prompt"] = job["_prompt"]                 # full prompt only in debug mode
    if job["_prompt"] is None:                         # missing-hints case, already errored
        rec.setdefault("error", "no prompt")
        rec.update({"parsed_answer": None, "raw_answer": "", "n_words": 0,
                    "n_words_reasoning": 0, "latency_s": 0.0})
        return rec
    name = f"templateF_{job['step']}_{job['request_id'][:8]}"
    out = run_codex(client, name, job["_prompt"], cfg.retries)
    parsed = out["parsed"]
    rec.update({
        "parsed_answer": parsed,
        "raw_answer": out["raw"],
        "n_words": len((out["raw"] or "").split()),
        "n_words_reasoning": _count_text_words(parsed),
        "latency_s": out["latency_s"],
        "returncode": out["returncode"],
        "parse_error": out["parse_error"],
        "stderr_preview": out["stderr_preview"],
        "codex_output_path": out["output_path"],
    })
    if parsed is None:
        rec["error"] = f"parse/generation failed: {out['parse_error']}"
    return rec


def save_record(run_dir: Path, job: dict[str, Any], rec: dict[str, Any]) -> None:
    path = per_problem_path(run_dir, job)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(rec, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


# ============================================================================
def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-n", "--num-problems", type=int, default=None,
                    help="process only the first N rows of EACH selected step. Default: all.")
    ap.add_argument("--steps", default="1,2,3,4,5",
                    help="comma list of step files to label (default 1,2,3,4,5)")
    ap.add_argument("--debug", action="store_true", default=True,
                    help="save under results/debug/ instead of results/runs/")
    ap.add_argument("--resume-dir", default=None,
                    help="continue a previous run dir (skips calls already saved there)")
    ap.add_argument("--workers", type=int, default=int(os.environ.get("MAX_WORKERS", "8")))
    ap.add_argument("--model", default=os.environ.get("CODEX_MODEL", "gpt-5.5"))
    ap.add_argument("--reasoning-effort", default=os.environ.get("CODEX_REASONING_EFFORT", "high"))
    ap.add_argument("--timeout", type=int, default=int(os.environ.get("CODEX_TIMEOUT_SECONDS", "900")))
    ap.add_argument("--retries", type=int, default=int(os.environ.get("RETRIES", "2")))
    ap.add_argument("--codex-bin", default=os.environ.get("CODEX_BIN", "codex"))
    return ap.parse_args()


def main() -> int:
    cfg = parse_args()
    steps = [int(s) for s in cfg.steps.split(",")]

    if cfg.resume_dir:
        run_dir = Path(cfg.resume_dir).resolve()
        run_dir.mkdir(parents=True, exist_ok=True)
        timestamp = run_dir.name
    else:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        base = RESULTS_ROOT / ("debug" if cfg.debug else "runs")
        run_dir = base / f"run_{timestamp}"
        run_dir.mkdir(parents=True, exist_ok=True)

    SESSION_DIR.mkdir(parents=True, exist_ok=True)

    # Dump the exact script + prompt + resolved config used for this run.
    shutil.copyfile(Path(__file__).resolve(), run_dir / Path(__file__).name)
    shutil.copyfile(prompt_template_F.__file__, run_dir / "prompt_template_F.py")
    (run_dir / "run_config.json").write_text(
        json.dumps({**vars(cfg), "steps": steps, "variant": VARIANT_NAME,
                    "run_dir": str(run_dir), "timestamp": timestamp}, indent=2),
        encoding="utf-8",
    )

    pid2hint = load_pid2hint()
    jobs = build_jobs(pid2hint, steps, cfg.num_problems, run_dir)
    print(f"variant={VARIANT_NAME} model={cfg.model} effort={cfg.reasoning_effort} "
          f"workers={cfg.workers} steps={steps} num_problems={cfg.num_problems} debug={cfg.debug}")
    print(f"run_dir={run_dir}")
    print(f"jobs to run: {len(jobs)}")
    if not jobs:
        return 0

    client = make_client(cfg)
    n_ok = n_fail = 0
    t_start = time.time()
    agg = (run_dir / "results.jsonl").open("a", encoding="utf-8")
    try:
        with ThreadPoolExecutor(max_workers=max(1, cfg.workers)) as ex:
            futs = {ex.submit(process, client, job, cfg): job for job in jobs}
            bar = tqdm(as_completed(futs), total=len(jobs), unit="row",
                       desc="Template F", dynamic_ncols=True, smoothing=0.1)
            for fut in bar:
                job = futs[fut]
                rec = fut.result()
                save_record(run_dir, job, rec)
                agg.write(json.dumps(rec, ensure_ascii=False) + "\n")
                agg.flush()
                if rec.get("error") is None:
                    n_ok += 1
                else:
                    n_fail += 1
                bar.set_postfix(ok=n_ok, fail=n_fail, refresh=False)
            bar.close()
    finally:
        agg.close()

    print(f"done: ok={n_ok} fail={n_fail}  wall={time.time()-t_start:.0f}s")
    print(f"results in {run_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
